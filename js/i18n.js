const DICTS = { ru, en };
let lang = 'ru';

export function setLang(l) { lang = DICTS[l] ? l : 'ru'; globalThis.document?.documentElement?.setAttribute('lang', lang); }
export function getLang() { return lang; }

export function t(key, params = {}) {
  let s = DICTS[lang][key] ?? DICTS.ru[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => {
    const v = params[k];
    if (v === undefined || v === null) return '';
    return typeof v === 'number' ? fmtNum(v, lang) : String(v);
  });
}

export function weekdayName(ts) {
  return new Intl.DateTimeFormat(lang === 'ru' ? 'ru-RU' : 'en-US', { weekday: 'long' }).format(new Date(ts));
}

export function fmtDate(ts, opts = { day: 'numeric', month: 'short' }) {
  return new Intl.DateTimeFormat(lang === 'ru' ? 'ru-RU' : 'en-US', opts).format(new Date(ts));
}

export function dayName(day) {
  return DICTS[lang][`day_${day}`] ? t(`day_${day}`) : t('day_other', { d: day });
}
